// Prints SQL that creates the DEMO farm's people as packhouse-server accounts (username = the part before @, password
// demo-password-123, no change required). Only for a separate demo / test instance (scripts/packhouse.sh install --demo).
import { DEMO_PASSWORD, USERS } from './demo-people.mjs';

const q = (s) => (s === null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const out = ["-- generated by scripts/appliance-demo-users.mjs (demo farm only)",
  "do $$ declare f uuid := (select id from public.farms where code = 'DEMO' and is_demo); u uuid; begin",
  "if f is null then raise exception 'demo farm missing'; end if;"];
for (const u of USERS) {
  out.push(`u := gen_random_uuid(); perform app.po_insert_auth_user(u, ${q(u.email)});`);
  out.push(`insert into public.user_profiles (id, farm_id, full_name) values (u, f, ${q(u.name)});`);
  out.push(`insert into app.po_accounts (user_id, farm_id, username, password_hash, must_change_password) values (u, f, ${q(u.email.split('@')[0])}, app.po_hash(${q(DEMO_PASSWORD)}), false);`);
  for (const [role, dept] of u.roles) {
    out.push(`insert into public.user_roles (farm_id, user_id, role_id, department_id, valid_from)
      select f, u, (select id from public.roles where farm_id = f and code = ${q(role)}),
             ${dept ? `(select id from public.departments where farm_id = f and code = ${q(dept)})` : 'null'}, now() - interval '1 day'
       where exists (select 1 from public.roles where farm_id = f and code = ${q(role)});`);
  }
}
out.push('end $$;');
console.log(out.join('\n'));
